import type { NextConfig } from "next";

/**
 * Cheap, safe security headers for every route. No full Content-Security-Policy
 * (Next.js inline scripts would need nonces); `frame-ancestors 'none'` +
 * X-Frame-Options block clickjacking. HSTS is ignored by browsers on
 * http://localhost and only takes effect on the HTTPS production domain.
 */
const securityHeaders = [
  { key: "X-Frame-Options", value: "DENY" },
  { key: "Content-Security-Policy", value: "frame-ancestors 'none'" },
  { key: "X-Content-Type-Options", value: "nosniff" },
  { key: "Referrer-Policy", value: "strict-origin-when-cross-origin" },
  { key: "Permissions-Policy", value: "camera=(), microphone=(), geolocation=(), browsing-topics=()" },
  { key: "Strict-Transport-Security", value: "max-age=63072000; includeSubDomains" },
];

const nextConfig: NextConfig = {
  poweredByHeader: false,
  async headers() {
    return [{ source: "/:path*", headers: securityHeaders }];
  },
};

export default nextConfig;
